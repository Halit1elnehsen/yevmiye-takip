class LocalizationProvider with ChangeNotifier {
  String _currentLanguage = 'tr'; // Varsayılan dil Türkçe

  String get currentLanguage => _currentLanguage;

  LocalizationProvider() {
    _loadLanguage();
  }

  Future<void> _loadLanguage() async {
    final lang = await DatabaseHelper.instance.getSetting('language');
    if (lang != null && lang.isNotEmpty) {
      _currentLanguage = lang;
      notifyListeners();
    }
  }

  Future<void> setLanguage(String languageCode) async {
    if (_currentLanguage != languageCode) {
      _currentLanguage = languageCode;
      await DatabaseHelper.instance.setSetting('language', languageCode);
      notifyListeners();
    }
  }

  String translate(String key) {
    return _localizedStrings[_currentLanguage]?[key] ?? key;
  }

